    items = []
    for line in lines:
        parts = line.split()
        berat = int(parts[0])
        kelas = " ".join(parts[1:]) # e.g. "Kelas 6B"
        items.append({
            "beratBadan": berat,
            "namaKelas": kelas
        })
    return items

